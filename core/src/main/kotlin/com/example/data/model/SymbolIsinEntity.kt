package com.example.data.model


/**
 * نگاشت نماد فارسی به کد ISIN، برای ساختن لینک فرم سفارش کارگزاری.
 *
 * **چرا ذخیره می‌شود و حدس زده نمی‌شود:** هیچ‌کدام از منابع داده برنامه
 * (FundBase) ISIN نمی‌دهند، و ساختنش از روی نماد فارسی فقط شبیه یک الگوست
 * («افران» ← `AFRN`)، نه قاعده‌ای که بشود به آن تکیه کرد. یک حرف اشتباه
 * یعنی فرم سفارشِ اوراق دیگری باز می‌شود.
 *
 * پس کاربر یک‌بار برای هر نماد آدرس فرم سفارش را می‌چسباند و همان‌جا
 * ذخیره می‌شود. سبد معمولی ده تا پانزده نماد دارد، پس این کار چند روزه
 * تمام می‌شود و دیگر تکرار نمی‌شود.
 */
data class SymbolIsinEntity(
    val symbol: String,

    /** کد ISIN، همیشه با حروف بزرگ ذخیره می‌شود. */
    val isin: String,

    /** آخرین باری که کاربر این کد را ثبت یا اصلاح کرد. */
    val updatedAtEpochMs: Long = 0L
)
