package com.example.data.model


data class PortfolioEntity(
    val id: Long = 0L,
    val symbol: String,
    val assetCategory: AssetCategory,
    /** ارزش روز ریالی */
    val currentValue: Double,
    /** تعداد واحد */
    val quantity: Long = 0L,
    /** قیمت روز هر واحد (ریال) */
    val lastPrice: Double = 0.0,
    /** قیمت سر به سر / میانگین خرید */
    val averagePrice: Double = 0.0,

    /**
     * نسبت «ارزش خالص» به «تعداد × قیمت روز»، یعنی یک منهای نرخ کارمزد فروش.
     *
     * ستون «ارزش فعلی» اکسل کارگزاری کارمزد فروش را از قبل کم کرده، ولی
     * بازمحاسبه با قیمت زنده این کار را نمی‌کرد؛ نتیجه‌اش این بود که سود سبد
     * بعد از هر رفرش به اندازه کارمزد فروش بالاتر می‌پرید، بدون اینکه بازار
     * تکان خورده باشد.
     *
     * نرخ از خود فایل کاربر در می‌آید (`ارزش فعلی ÷ (تعداد × آخرین قیمت)`) و
     * برای هر نماد فرق دارد: صندوق سهامی حدود ۰٫۲۳٪، طلا ۰٫۱۲٪، درآمد ثابت
     * ۰٫۰۴٪ و سهم عادی نزدیک ۰٫۸۸٪. هیچ نرخی در کد هاردکد نشده.
     *
     * ۱٫۰ یعنی نامعلوم، و همان رفتار قبلی را می‌دهد.
     */
    val netValueRatio: Double = 1.0,
    /** درصد هدف اختصاصی این نماد (اختیاری) */
    val manualTargetPercent: Double? = null,

    /**
     * true یعنی کاربر ارزش این ردیف را خودش وارد کرده و همگام‌سازی قیمت زنده
     * حق بازنویسی آن را ندارد. بدون این پرچم، هر بار رفرش، عددی که کاربر
     * وارد کرده بود با `quantity × قیمت زنده` جایگزین می‌شد.
     */
    val isValueManuallySet: Boolean = false,

    /**
     * true یعنی دسته‌بندی را کاربر دستی انتخاب کرده و تطبیق خودکار نمادها
     * نباید آن را تغییر دهد.
     */
    val isCategoryManuallySet: Boolean = false,

    /**
     * «قفل نگه‌داری»: کاربر تصمیم گرفته این نماد را نگه دارد و موتور حق ندارد
     * برای آن پیشنهاد فروش بدهد — حتی وقتی وزنش از هدف بیشتر است.
     *
     * کاربرد اصلی‌اش طلاست در دوره‌های پرریسک: به‌جای فروش طلا برای بازتعادل،
     * موتور حساب می‌کند چقدر پول نقد لازم است تا وزن طلا خودبه‌خود به هدف برسد
     * و همان مبلغ را بین بقیه صندوق‌ها پخش می‌کند.
     *
     * قفل فقط جلوی **فروش** را می‌گیرد؛ اگر نماد قفل‌شده کم‌وزن باشد همچنان
     * پیشنهاد خرید می‌گیرد.
     */
    val isHoldLocked: Boolean = false
)
